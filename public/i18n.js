window.t = function (key) {
  const lang = window.__atlasLang || window.ATLAS_CONFIG.defaultLang;
  const dict = window.ATLAS_I18N[lang] || window.ATLAS_I18N.de;
  return dict[key] || key;
};

window.setLang = function (lang) {
  window.__atlasLang = lang;
  localStorage.setItem("atlas-lang", lang);
  document.documentElement.lang = lang;
  document.dispatchEvent(new CustomEvent("atlas:lang-changed", { detail: lang }));
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    el.textContent = window.t(k);
  });
  // Erlaubt eingebettetes HTML (<em>, <strong>), nur auf vertrauenswürdige Keys anwenden
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const k = el.getAttribute("data-i18n-html");
    el.innerHTML = window.t(k);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const k = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", window.t(k));
  });
  // Dokumenttitel (wenn ein Element mit data-i18n-title existiert, wird dessen
  // Wert in document.title gespiegelt)
  const titleKey = document.documentElement.getAttribute("data-i18n-title");
  if (titleKey) document.title = window.t(titleKey);
};

// ---- Datumsformat ----
// Liefert das passende Locale für die aktuelle Sprache. Außerhalb von DE/EN
// fällt es auf das Browser-Default zurück.
window.atlasLocale = function () {
  return window.__atlasLang === "en" ? "en-GB" : "de-DE";
};

// Kurzdatum: 24.04.2026 (de) bzw. 24/04/2026 (en-GB)
window.formatDate = function (input, opts) {
  if (input == null || input === "") return "—";
  const d = input instanceof Date ? input : new Date(input);
  if (isNaN(d.getTime())) return "—";
  return d.toLocaleDateString(
    window.atlasLocale(),
    opts || { day: "2-digit", month: "2-digit", year: "numeric" }
  );
};

// Datum + Uhrzeit
window.formatDateTime = function (input) {
  if (input == null || input === "") return "—";
  const d = input instanceof Date ? input : new Date(input);
  if (isNaN(d.getTime())) return "—";
  return d.toLocaleString(window.atlasLocale());
};

// Langes Datum (für Eventkarten): „Sa., 24. April 2026" / „Sat, 24 April 2026"
window.formatDateLong = function (input) {
  return window.formatDate(input, {
    weekday: "short", day: "2-digit", month: "long", year: "numeric",
  });
};

// Preis: 2,50 (de) / 2.50 (en)
window.formatPrice = function (n) {
  const s = Number(n).toFixed(2);
  return window.__atlasLang === "en" ? s : s.replace(".", ",");
};

// Größenangabe: 0,25 l (de) / 0.25 l (en)
// Akzeptiert neue Dezimalform "0.25" und Legacy-Form "0,25l"
window.formatSize = function (s) {
  if (!s) return "";
  const num = parseFloat(String(s).replace(",", ".").replace(/\s*l$/i, ""));
  if (isNaN(num)) return String(s);
  let dec = num.toFixed(2).replace(/0+$/, "").replace(/\.$/, "");
  if (window.__atlasLang !== "en") dec = dec.replace(".", ",");
  return dec + " l";
};

