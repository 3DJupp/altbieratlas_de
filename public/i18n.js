window.atlasLocale = function () {
  return window.__atlasLang === "en" ? "en-GB" : "de-DE";
};

// Kurzdatum: 24.04.2026 (de) bzw. 24/04/2026 (en-GB)
window.formatDate = function (input, opts) {
  if (input == null || input === "") return "—";
  const d = input instanceof Date ? input : new Date(input);
  if (isNaN(d.getTime())) return "—";
  return d.toLocaleDateString(
    window.atlasLocale(),
    opts || { day: "2-digit", month: "2-digit", year: "numeric" }
  );
};

// Datum + Uhrzeit
window.formatDateTime = function (input) {
  if (input == null || input === "") return "—";
  const d = input instanceof Date ? input : new Date(input);
  if (isNaN(d.getTime())) return "—";
  return d.toLocaleString(window.atlasLocale());
};

// Langes Datum (für Eventkarten): „Sa., 24. April 2026" / „Sat, 24 April 2026"
window.formatDateLong = function (input) {
  return window.formatDate(input, {
    weekday: "short", day: "2-digit", month: "long", year: "numeric",
  });
};

// Preis: 2,50 (de) / 2.50 (en)
window.formatPrice = function (n) {
  const s = Number(n).toFixed(2);
  return window.__atlasLang === "en" ? s : s.replace(".", ",");
};

// Alkoholgehalt: 4,8 % (de) / 4.8 % (en)
window.formatABV = function (n) {
  if (n == null) return null;
  const s = Number(n).toFixed(1);
  return (window.__atlasLang === "en" ? s : s.replace(".", ",")) + " %";
};

// Größenangabe: 0,25 l (de) / 0.25 l (en)
// Akzeptiert neue Dezimalform "0.25" und Legacy-Form "0,25l"
window.formatSize = function (s) {
  if (!s) return "";
  const num = parseFloat(String(s).replace(",", ".").replace(/\s*l$/i, ""));
  if (isNaN(num)) return String(s);
  let dec = num.toFixed(3).replace(/0+$/, "").replace(/\.$/, "");
  if (window.__atlasLang !== "en") dec = dec.replace(".", ",");
  return dec + " l";
};

