window.t = function (key) {
  const lang = window.__atlasLang || window.ATLAS_CONFIG.defaultLang;
  const dict = window.ATLAS_I18N[lang] || window.ATLAS_I18N.de;
  return dict[key] || key;
};

window.setLang = function (lang) {
  window.__atlasLang = lang;
  localStorage.setItem("atlas-lang", lang);
  document.documentElement.lang = lang;
  document.dispatchEvent(new CustomEvent("atlas:lang-changed", { detail: lang }));
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    el.textContent = window.t(k);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const k = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", window.t(k));
  });
};

(function () {
  const stored = localStorage.getItem("atlas-lang");
  window.__atlasLang = stored || (window.ATLAS_CONFIG && window.ATLAS_CONFIG.defaultLang) || "de";
  document.documentElement.lang = window.__atlasLang;
})();
